public class DataTypes {
    public static void main(String[] args) {

        // Integer (Whole Number) - ကိန်းပြည့်
        int age = 22;

        // Float (Decimal Number - 32 bit) - ဒဿမကိန်း (32-bit)
        float height = 170.5f;

        // Double (Decimal Number - 64 bit) - ဒဿမကိန်း (64-bit)
        double salary = 250000.75;

        // Character (Single Character) - စာလုံးတစ်လုံး
        char grade = 'A';

        // Boolean (True or False) - အမှန် / အမှား
        boolean isStudent = true;

        // String (Text) - စာသား
        String name = "Yamin";

        //String (Text) - စာသား
        String country = "MYANMAR";

        // Byte (Small Integer) - ကိန်းပြည့်အသေး
        byte number = 100;

        // Short (Short Integer) - ကိန်းပြည့်
        short year = 2026;

        // Long (Large Integer) - ကိန်းပြည့်အကြီး
        long population = 8000000000L;

        // Print Output - ရလဒ်ထုတ်ပြခြင်း
        System.out.println("Name       : " + name);
        System.out.println("Country     : " + country);
        System.out.println("Age        : " + age);
        System.out.println("Height     : " + height);
        System.out.println("Salary     : " + salary);
        System.out.println("Grade      : " + grade);
        System.out.println("Student    : " + isStudent);
        System.out.println("Byte       : " + number);
        System.out.println("Year       : " + year);
        System.out.println("Population : " + population);
    }
}